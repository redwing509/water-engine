def foam(path, obj, body, cls="dictionary", loc=""):
    path.parent.mkdir(parents=True, exist_ok=True)
    l = f'location    "{loc}";\n    ' if loc else ""
    path.write_text(HDR.format(cls=cls, obj=obj, loc=l) + body + "\n// ************************************************************************* //\n")

# ---------------------------------------------------------------- design inputs
def design_inputs():
    """Module 03 CH3OH water-majority design point, vendored (with provenance and
    sha256) in design_inputs.json because module 03 results are not on wme1-cfd."""
    return json.loads((HERE / "design_inputs.json").read_text())

