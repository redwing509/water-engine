# ---------------------------------------------------------------- STL
def write_stl(path, g, nseg=96):
    Rp, Rs, Rv, Rb = g["D_port"]/2, g["d_stem"]/2, g["D_valve"]/2, g["bore"]/2
    Lp, L, t, H = g["L_port"], g["lift"], g["t_valve"], g["H_cyl"]
    # closed (r, z) profile of the fluid domain, counter-clockwise, with region tags
    segs = [((Rs, Lp), (Rp, Lp), "inlet"),
            ((Rp, Lp), (Rp, 0.0), "walls"),
            ((Rp, 0.0), (Rb, 0.0), "walls"),
            ((Rb, 0.0), (Rb, -H), "walls"),
            ((Rb, -H), (0.0, -H), "outlet"),
            ((0.0, -L - t), (Rv, -L - t), "walls"),
            ((Rv, -L - t), (Rv, -L), "walls"),
            ((Rv, -L), (Rs, -L), "walls"),
            ((Rs, -L), (Rs, Lp), "walls")]
    tris = {"inlet": [], "outlet": [], "walls": []}
    ang = [2*math.pi*i/nseg for i in range(nseg + 1)]
    def P(r, z, a): return (r*math.cos(a), r*math.sin(a), z)
    for (r0, z0), (r1, z1), reg in segs:
        # subdivide long segments so the surface has reasonable triangles
        n = max(1, int(math.hypot(r1 - r0, z1 - z0) / 0.004))
        for k in range(n):
            ra, za = r0 + (r1 - r0)*k/n, z0 + (z1 - z0)*k/n
            rb, zb = r0 + (r1 - r0)*(k+1)/n, z0 + (z1 - z0)*(k+1)/n
            for i in range(nseg):
                a0, a1 = ang[i], ang[i+1]
                p00, p01 = P(ra, za, a0), P(ra, za, a1)
                p10, p11 = P(rb, zb, a0), P(rb, zb, a1)
                if ra > 1e-12: tris[reg].append((p00, p10, p01))
                if rb > 1e-12: tris[reg].append((p01, p10, p11))
    def nrm(a, b, c):
        u = [b[i]-a[i] for i in range(3)]; v = [c[i]-a[i] for i in range(3)]
        n = (u[1]*v[2]-u[2]*v[1], u[2]*v[0]-u[0]*v[2], u[0]*v[1]-u[1]*v[0])
        m = math.sqrt(sum(x*x for x in n)) or 1.0
        return tuple(x/m for x in n)
    with open(path, "w") as f:
        for reg, ts in tris.items():
            f.write(f"solid {reg}\n")
            for a, b, c in ts:
                n = nrm(a, b, c)
                f.write(f" facet normal {n[0]:.6e} {n[1]:.6e} {n[2]:.6e}\n  outer loop\n")
                for p in (a, b, c): f.write(f"   vertex {p[0]:.7e} {p[1]:.7e} {p[2]:.7e}\n")
                f.write("  endloop\n endfacet\n")
            f.write(f"endsolid {reg}\n")
    return {k: len(v) for k, v in tris.items()}

# ---------------------------------------------------------------- case
def make_case(name, inj, mesh, d, out=None):
    g = dict(GEOM); U_port = U_PORT
    flag = "carb_design.json not committed on wme1-dev; 34 mm / 30 m/s fallback port"
    cone = INJ[inj].get("cone"); cp = carb_port()
    if cone and cp:      # the new cone-injector cases use the module 06 port
        g["D_port"] = cp["D_port"]; U_port = cp["U_port"]
        flag = f"port from module 06 carb_design.json ({cp['source']}): D_port = throttle bore, U_port = event-mean"
    case = (out or (CFD / "runs")) / name
    if case.exists():
        if any((case / x).exists() for x in ("processor0", "log.Allrun", "postProcessing")) and not os.environ.get("M13_FORCE"):
            raise SystemExit(f"{case} has run output; refusing to overwrite (set M13_FORCE=1)")   # 2026-10-24 incident
        shutil.rmtree(case)
    (case / "constant/triSurface").mkdir(parents=True)
    ntri = write_stl(case / "constant/triSurface/port.stl", g)

    t_deg = 1.0 / (6.0 * d["rpm"])               # s per crank degree
    t_inj = 180.0 * t_deg                        # one intake event
    t_pre = 0.008                                # gas-only precursor
    t_end = t_pre + t_inj
    m_liq = d["m_liq_cycle_kg"]
    smd = INJ[inj]["smd"]
    lam = smd / math.gamma(1.0 - 1.0/RR_N)       # mass-based Rosin-Rammler: D32 = lambda/Gamma(1-1/n)
    pps = 3.0e6 if mesh == "coarse" else 6.0e6
    T0 = d["T_intake_K"]
    m = MESH[mesh]; dx = m["dx"]
    Rb = g["bore"]/2
    x0, x1 = -Rb - 2*dx, Rb + 2*dx
    z0, z1 = -g["H_cyl"] - 2*dx, g["L_port"] + 2*dx
    nx = int(round((x1 - x0)/dx)); nz = int(round((z1 - z0)/dx))
    meta = dict(case=name, injector=inj, injector_label=INJ[inj]["label"], mesh=mesh,
                smd_m=smd, rosin_rammler_lambda_m=lam, rosin_rammler_n=RR_N,
                geometry=g, U_port_m_s=U_port, flagged=flag, carb_port=cp if cone else None,
                design=d, t_deg_s=t_deg, t_precursor_s=t_pre, t_inject_s=t_inj, t_end_s=t_end,
                ivc_definition="end of one intake event (180 CA at module 03 rpm) after SOI; t_end",
                m_liq_injected_kg=m_liq, parcels_per_second=pps, stl_triangles=ntri,
                film_liquid="H2O (single-component film; blend droplets)", T_wall_K=T0,
                background_cells=[nx, nx, nz])
    (case / "case_meta.json").write_text(json.dumps(meta, indent=2))

    # ---- system
