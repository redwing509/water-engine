def carb_port():
    """Port size/velocity from module 06 carb_design.json (vendored in design_inputs.json["carb"]):
    D_port = throttle bore; U_port = intake-event-mean air velocity
    = 4 * cycle-mean air mass flow / (rho_intake * A_port)   (intake event = 180 of 720 CA)."""
    c = design_inputs().get("carb")
    if not c: return None
    rho = c["p_manifold_Pa"] / (287.05 * c["T_intake_K"])
    A = math.pi * c["throttle_bore_diameter_m"]**2 / 4
    return dict(D_port=c["throttle_bore_diameter_m"], U_port=4 * c["air_mass_flow_kg_s"] / (rho * A),
                U_port_peak=c["maximum_event_air_mass_flow_kg_s"] / (rho * A), rho_intake=rho, source=c["source"])

